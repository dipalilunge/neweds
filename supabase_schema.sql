create table if not exists public.admissions (
    id bigint generated by default as identity primary key,
    created_at timestamptz not null default now(),
    timestamp text not null,
    student_name text not null,
    course_name text,
    course_fees text,
    aadhar_number text,
    college_name text,
    mobile_number text,
    address text,
    placement_details text,
    payment_method text,
    transaction_id text,
    batch_name text,
    batch_id text
);

create index if not exists admissions_student_name_lower_idx
    on public.admissions (lower(student_name));

create table if not exists public.service_enquiries (
    id bigint generated by default as identity primary key,
    created_at timestamptz not null default now(),
    timestamp text not null,
    name text not null,
    email text not null,
    phone text,
    service_category text,
    service_required text,
    message text
);

alter table public.admissions enable row level security;
alter table public.service_enquiries enable row level security;

grant all on public.admissions, public.service_enquiries to service_role;
grant usage, select on all sequences in schema public to service_role;
